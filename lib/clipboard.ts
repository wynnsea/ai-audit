// navigator.clipboard hanya ada di HTTPS atau localhost. Kalau aplikasi dibuka lewat IP biasa
// (misal http://192.168.x.x:3000), dipakai cara lama: textarea tersembunyi + execCommand("copy").
export async function copyText(text: string): Promise<boolean> {
  if (navigator.clipboard && window.isSecureContext) {
    try {
      await navigator.clipboard.writeText(text);
      return true;
    } catch {
      // jatuh ke cara lama di bawah
    }
  }

  const area = document.createElement("textarea");
  area.value = text;
  area.setAttribute("readonly", "");
  area.style.position = "fixed";
  area.style.opacity = "0";
  document.body.appendChild(area);
  area.select();
  try {
    return document.execCommand("copy");
  } catch {
    return false;
  } finally {
    area.remove();
  }
}
